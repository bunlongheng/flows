// Bakes the OG card's fonts into a JS module, the same trick scripts/gen-icon-manifest.mjs
// uses for logos. A Vercel serverless function has no system fonts and no reliable
// read access to repo files, but it CAN import a module - so the bytes travel with
// the bundle and get written to /tmp on first render.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "lib", "fonts");
const out = {};
for (const f of ["Roboto-Regular.ttf", "Roboto-Bold.ttf", "Inter-Regular.ttf", "Inter-SemiBold.ttf", "Inter-Bold.ttf"]) {
  out[f] = readFileSync(path.join(dir, f)).toString("base64");
}
writeFileSync(
  path.join(dir, "..", "font-data.js"),
  `// AUTO-GENERATED by scripts/gen-font-data.mjs - do not edit.\nexport default ${JSON.stringify(out)};\n`,
);
console.log(`font-data.js: ${Object.keys(out).length} fonts`);
